const WEEKDAYS: Record<Locale, string[]> = {
  ja: ["日", "月", "火", "水", "木", "金", "土"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
};

/** 曜日の短い名前 */
export const weekdayName = (day: number, locale: Locale) => WEEKDAYS[locale][day];

const DIRECTIONS: Record<Locale, string[]> = {
  ja: ["北", "北北東", "北東", "東北東", "東", "東南東", "南東", "南南東", "南", "南南西", "南西", "西南西", "西", "西北西", "北西", "北北西"],
  en: ["N", "NNE", "NE", "ENE", "E", "ESE", "SE", "SSE", "S", "SSW", "SW", "WSW", "W", "WNW", "NW", "NNW"],
};

/** 風の吹いてくる向き（度）を16方位の名前にする */
export const directionName = (degrees: number, locale: Locale) => DIRECTIONS[locale][Math.round(degrees / 22.5) % 16];

/** 天気の名前。日本語はサーバーの condition（いままでと同じ文）、英語は天気コードから引く */
export const conditionText = (code: number, ja: string, locale: Locale) => weatherConditionText(code, ja, locale);
